/**
 * -----------------------------------------------------------------------------
 * File: search.api.ts
 * Feature: Search
 *
 * Purpose:
 * Provides HTTP access to the Marketplace Search backend.
 *
 * Responsibilities:
 * - Execute marketplace search requests.
 * - Deserialize backend responses.
 * - Validate transport responses.
 * - Never perform business logic or UI mapping.
 *
 * Architecture:
 *
 * UI
 *   ↓
 * Hook
 *   ↓
 * Search Service
 *   ↓
 * Search API
 *   ↓
 * Express Backend
 * -----------------------------------------------------------------------------
 */

export interface SearchOfferDto {
  id: string;
  productId: string;
  title: string;
  brand?: string;
  price: number;
  originalPrice?: number;
  discountPercentage?: number;
  currency: string;
  imageUrl: string;
  productUrl: string;
  marketplace: string;
  inStock: boolean;
  rating?: number;
  dataSource?: "live" | "persisted-snapshot";
  observedAt?: string;
  availabilityStatus?: "in-stock" | "out-of-stock" | "unverified";
}

export interface SearchAiPredictionDto {
  direction: "up" | "down" | "stable";
  change_percentage: number;
  confidence: number;
  explanation: string;
  sample_size?: number;
  method?:
    | "baseline-collecting"
    | "historical-linear-regression"
    | "historical-price-stability"
    | "historical-price-trend"
    | "marketplace-spread-signal"
    | "live-marketplace-signals";
}

export interface SearchAiRecommendationDto {
  action: string;
  priority: "high" | "medium" | "low";
  reason: string;
}

export interface SearchAiAnalysisDto {
  relevance_score: number;
  relevance_reason: string;
  insight: string;
  confidence_score: number;
  evaluation_score: number;
  risk_level: "high" | "medium" | "low";
  variant_verification: {
    status: "verified" | "review" | "conflict" | "insufficient";
    confidence: number;
    summary: string;
    matched_attributes: string[];
    conflicting_attributes: string[];
    incomplete_attributes: string[];
  };
  savings_percentage: number;
  price_volatility_score: number;
  prediction: SearchAiPredictionDto;
  recommendation: SearchAiRecommendationDto;
}

/**
 * Represents one grouped search result returned
 * by the Marketplace backend.
 */
export interface SearchResultDto {
  /**
   * Normalized comparison key generated by the backend.
   */
  comparisonKey: string;

  /**
   * Number of marketplace offers in this group.
   */
  offerCount: number;

  /**
   * Marketplace offers belonging to the same product.
   */
  offers: SearchOfferDto[];

  /**
   * AI intelligence generated by the backend before returning the result.
   */
  aiAnalysis?: SearchAiAnalysisDto;
}

/**
 * Standard API response returned by the backend.
 */
interface SearchApiResponse {
  success: boolean;
  count: number;
  data: SearchResultDto[];
}

const API_BASE_URL =
  import.meta.env.VITE_API_BASE_URL ?? "http://localhost:5000";

/**
 * Searches the Marketplace backend.
 *
 * @param query User search keyword.
 *
 * @returns Grouped marketplace search results.
 */
export async function fetchSearchResults(
  query: string,
): Promise<SearchResultDto[]> {
  /**
   * Remove accidental whitespace.
   */
  const keyword = query.trim();

  /**
   * Avoid unnecessary API requests.
   */
  if (!keyword) {
    return [];
  }

  /**
   * Execute the search request.
   */
  const response = await authenticatedFetch(
    `${API_BASE_URL}/api/v1/marketplace/search?q=${encodeURIComponent(keyword)}`,
  );

  /**
   * Handle transport failures.
   */
  if (!response.ok) {
    throw new Error(`Marketplace search failed (${response.status}).`);
  }

  /**
   * Deserialize the backend response.
   */
  const body: SearchApiResponse = await response.json();

  /**
   * Validate the response contract.
   */
  if (!body.success) {
    throw new Error("Marketplace search was unsuccessful.");
  }

  return body.data;
}
import { authenticatedFetch } from "@/features/auth/services/authenticated-fetch";
